CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE courts (
    id INTEGER PRIMARY KEY,
    name VARCHAR(255) NOT NULL
);

INSERT INTO courts (id, name) VALUES (1, 'Tennis Court'), (2, 'Basketball Court');

CREATE TABLE bookings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    court_id INTEGER NOT NULL REFERENCES courts(id),
    booking_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    CONSTRAINT valid_booking_time CHECK (
        start_time >= TIME '08:00' AND end_time <= TIME '22:00' AND start_time < end_time
        AND MOD(EXTRACT(EPOCH FROM start_time), 1800) = 0
        AND MOD(EXTRACT(EPOCH FROM end_time), 1800) = 0
    ),
    CONSTRAINT no_overlapping_bookings EXCLUDE USING gist (
        court_id WITH =,
        tsrange(booking_date + start_time, booking_date + end_time, '[)') WITH &&
    )
);
